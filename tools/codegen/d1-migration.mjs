#!/usr/bin/env node
// Generates worker/migrations/0001_problem_reports.sql (add-problem-reporting
// design R6) from data/report-limits.json, so the D1 CHECK constraints use the
// same limits as the client, the Worker, and the MCP report tool.
// Usage: node tools/codegen/d1-migration.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../..', import.meta.url).pathname;
const L = JSON.parse(readFileSync(join(root, 'data/report-limits.json'), 'utf8'));
const kinds = L.kinds.map((k) => `'${k}'`).join(',');

export const sql = `-- 0001_problem_reports.sql: generated by tools/codegen/d1-migration.mjs from
-- data/report-limits.json. Do not edit; change the limits file and regenerate.
CREATE TABLE problem_reports (
  id TEXT PRIMARY KEY NOT NULL,
  created_at TEXT NOT NULL,
  tool_id TEXT NOT NULL,
  tool_version TEXT NOT NULL,
  core_version TEXT NOT NULL,
  build_hash TEXT NOT NULL,
  asset_versions_json TEXT NOT NULL CHECK (length(asset_versions_json) <= ${L.assetVersionsJsonChars}),
  kind TEXT NOT NULL CHECK (kind IN (${kinds})),
  page_path TEXT NOT NULL CHECK (length(page_path) <= ${L.pagePathChars}),
  note TEXT CHECK (note IS NULL OR length(note) <= ${L.noteChars}),
  note_has_url INTEGER NOT NULL DEFAULT 0 CHECK (note_has_url IN (0,1)),
  inputs_json TEXT NOT NULL CHECK (length(inputs_json) <= ${L.inputsJsonChars}),
  outputs_json TEXT NOT NULL CHECK (length(outputs_json) <= ${L.outputsJsonChars}),
  warnings_json TEXT NOT NULL CHECK (length(warnings_json) <= ${L.warningsJsonChars}),
  display_json TEXT NOT NULL CHECK (length(display_json) <= ${L.displayJsonChars}),
  dedupe_key TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN
    ('open','triaged','confirmed','fixed','wont_fix','duplicate','not_a_bug')),
  primary_source TEXT CHECK (primary_source IS NULL OR length(primary_source) <= 1000),
  resolution_note TEXT CHECK (resolution_note IS NULL OR length(resolution_note) <= 1000),
  fixed_in_version TEXT,
  resolved_at TEXT
);
CREATE INDEX pr_status_kind_created ON problem_reports (status, kind, created_at);
CREATE INDEX pr_tool_status ON problem_reports (tool_id, status);
CREATE TABLE report_limits (
  bucket TEXT NOT NULL,
  scope TEXT NOT NULL CHECK (scope IN ('global','reporter')),
  subject TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('attempt','accepted')),
  count INTEGER NOT NULL CHECK (count >= 0),
  PRIMARY KEY (bucket, scope, subject, kind)
) WITHOUT ROWID;
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = join(root, 'worker/migrations/0001_problem_reports.sql');
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== sql) {
      console.error(`${path} is stale: run node tools/codegen/d1-migration.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(path, sql);
    console.log(`wrote ${path}`);
  }
}
