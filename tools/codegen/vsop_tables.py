#!/usr/bin/env python3
"""Regenerates core/crates/gp-astro/src/vsop_tables.rs: the VSOP87D series
(Bretagnon and Francou 1988; heliocentric ecliptic of date: longitude L,
latitude B in radians, radius R in au, in Julian millennia of TDB) for the
Earth, Venus, Mars, Jupiter, and Saturn, keeping the terms of amplitude at
least CUTOFF. Measured 1900-2100 against the full series, the cut keeps
every body's geocentric position within 2.2 arcseconds.

Download the five files from VizieR (https://cdsarc.cds.unistra.fr/ftp/VI/81/:
VSOP87D.ear, .ven, .mar, .jup, .sat) into a directory, then:

    vsop_tables.py DIR [OUT]

Standard library only."""
import sys
from pathlib import Path

CUTOFF = 3e-7
BODIES = [("EARTH", "ear"), ("VENUS", "ven"), ("MARS", "mar"), ("JUPITER", "jup"), ("SATURN", "sat")]


def read(path):
    series, cur = {}, None
    for line in path.read_text().splitlines():
        if line.startswith(" VSOP87"):
            var = int(line.split("VARIABLE")[1].split()[0])
            power = int(line.split("*T**")[1].split()[0])
            cur = series.setdefault(var, {}).setdefault(power, [])
            continue
        f = line.split()
        if f:
            cur.append((float(f[-3]), float(f[-2]), float(f[-1])))
    return series


src = Path(sys.argv[1])
dest = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[2] / "core" / "crates" / "gp-astro" / "src" / "vsop_tables.rs"
out = [
    "//! VSOP87D series (Bretagnon and Francou 1988, VizieR VI/81) for the Earth,",
    "//! Venus, Mars, Jupiter, and Saturn: heliocentric ecliptic and equinox of",
    f"//! date, terms A cos(B + C tau) with A at least {CUTOFF}, tau in Julian",
    "//! millennia of TDB from J2000.0. Generated by tools/codegen/vsop_tables.py.",
    "//! Do not edit by hand.",
    "",
    "#![allow(clippy::approx_constant, clippy::unreadable_literal, clippy::excessive_precision)]",
    "",
    "/// One coordinate: its series for powers of tau 0 to 5.",
    "pub type Series = [&'static [[f64; 3]]; 6];",
    "",
]
kept = total = 0
for name, ext in BODIES:
    s = read(src / f"VSOP87D.{ext}")
    for var, coord in ((1, "L"), (2, "B"), (3, "R")):
        out.append(f"pub const {name}_{coord}: Series = [")
        for p in range(6):
            terms = [t for t in s.get(var, {}).get(p, []) if t[0] >= CUTOFF]
            total += len(s.get(var, {}).get(p, []))
            kept += len(terms)
            out.append("    &[" + ", ".join(f"[{a!r}, {b!r}, {c!r}]" for a, b, c in terms) + "],")
        out.append("];")
dest.write_text("\n".join(out) + "\n")
print(f"wrote {dest}: {kept} of {total} terms")
